'use strict';
const assert=require('node:assert/strict');
const {automaticPlacement}=require('../src/automatic-placement');
const {htmlCopyContext}=require('../src/html-context');
const {workflowOptions}=require('../src/workflow-options');
const safety=require('../src/safe-placement');
const placement=require('../src/placement');
const options=workflowOptions({workspace:{}});
function copy(html,name){return htmlCopyContext(html,{name,start:html.indexOf(name)});}
function insert(css,selector,context,opts=options,request={}){
  const action=automaticPlacement(css,selector,context,opts,request);
  assert.equal(action.kind,'insert',JSON.stringify(action));
  const checked=safety.preflight(css,selector,action.insertion,'css',action.commentText);
  assert.equal(checked.ok,true,JSON.stringify(checked));
  return {after:checked.after,action};
}
const html='<header class="hero"><a class="brand"></a></header><section class="news"><h2 class="title"></h2><p class="body"></p><a class="link"></a></section><footer class="footer"></footer>';
const body=copy(html,'body');
const first=insert('','.body',body);
assert.equal(first.after,'/* news\n--------------------------------*/\n\n.body {\n}\n');
const css='/* news\n--------------------------------*/\n.title {}\n.link {}\n/* footer\n--------------------------------*/\n.footer {}\n';
const ordered=insert(css,'.body',body).after;
assert.ok(ordered.indexOf('.title')<ordered.indexOf('.body'));
assert.ok(ordered.indexOf('.body')<ordered.indexOf('.link'));
assert.equal((ordered.match(/\/\* news/g)||[]).length,1);
const footer='/* footer\n--------------------------------*/\n.footer {}\n';
const beforeFooter=insert(footer,'.body',body).after;
assert.ok(beforeFooter.indexOf('/* news')<beforeFooter.indexOf('/* footer'));
const sharedHtml='<header><div class="l-inner"></div></header><section class="news"><div class="l-inner"></div></section>';
const shared=copy(sharedHtml,'l-inner');
assert.equal(shared.structure.overview.sharedAcrossRegions,true);
assert.equal(shared.structure.overview.occurrenceCount,2);
assert.equal(shared.structure.overview.regionCount,2);
const common=insert('','.l-inner',shared).after;
assert.ok(common.startsWith('/* 仮置き: 共通\n'));
assert.ok(!common.includes('/* header'));
const within=copy('<section class="news"><b class="item"></b><i class="item"></i></section>','item');
assert.equal(within.structure.overview.sharedAcrossRegions,false);
assert.equal(within.structure.overview.occurrenceCount,2);
const unknown=insert('','.card__title',null).after;
assert.ok(unknown.startsWith('/* 仮置き: card\n'));
const reused=insert(unknown,'.card__body',null).after;
assert.equal((reused.match(/仮置き: card/g)||[]).length,1);
const existing=automaticPlacement('.body {}\n@media screen { .body {} }','.body',body,options,{offset:0});
assert.equal(existing.kind,'jump');assert.equal(existing.rule.parent.type,'root');
const media='@media screen {\r\n}\r\n';
const mediaResult=insert(media,'.body',body,options,{offset:media.indexOf('}')});
const added=placement.rules(placement.parseCss(mediaResult.after)).find(r=>r.prelude==='.body');
assert.equal(added.parent.prelude,'@media screen');
assert.equal((mediaResult.after.match(/@media/g)||[]).length,1);
assert.ok(!/(?<!\r)\n/.test(mediaResult.after));
const beforeQuery=insert(media,'.body',body,options,{offset:0}).after;
assert.ok(beforeQuery.indexOf('.body')<beforeQuery.indexOf('@media'));
const configured=insert(media,'.body',body,options,{offset:0,configuredScope:'@media screen'}).after;
assert.equal(placement.rules(placement.parseCss(configured)).find(r=>r.prelude==='.body').parent.prelude,'@media screen');
const repeatedMedia='@media screen { /* news\n--------------------------------*/ .body {} }\n@media screen {\n}\n';
const local=insert(repeatedMedia,'.body',body,options,{offset:repeatedMedia.lastIndexOf('}')});
assert.equal((local.after.match(/\/\* news/g)||[]).length,2,'An identical query in another block must not suppress the local landmark');
assert.equal((local.after.match(/\.body/g)||[]).length,2,'An existing rule in a different query block must not hijack the current block');
const nestedExact=insert('.wrapper { .body {} }','.body',body).after;
assert.equal(placement.rules(placement.parseCss(nestedExact)).filter(r=>r.prelude==='.body').length,2,'A nested class does not replace the requested top-level class');
const nested='/* news\n--------------------------------*/\n.wrapper { .title {} .link {} }\n/* footer\n--------------------------------*/\n.footer {}';
const nestedResult=insert(nested,'.body',body).after;
assert.equal(placement.rules(placement.parseCss(nestedResult)).find(r=>r.prelude==='.body').parent.type,'root');
assert.ok(nestedResult.indexOf('.body')<nestedResult.indexOf('/* footer'));
const disabled=automaticPlacement('','.body',null,{...options,addComments:false});
assert.equal(disabled.kind,'error');
assert.equal(automaticPlacement('.broken {','.body',body,options).kind,'error');
const invalidTemplate=automaticPlacement('','.body',body,{...options,commentTemplate:'/* x */ .evil {}'});
assert.equal(invalidTemplate.kind,'error');
console.log('automatic-placement-tests: landmarks, source order, shared classes, scope, reuse and safe edits passed');
