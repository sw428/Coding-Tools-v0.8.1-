'use strict';
const assert = require('node:assert/strict');
const {classAt,findTargets,lineAt} = require('../cross-navigation');
const html = `<section class="card active"><h2 class="card__title">Hello</h2><p class=""></p></section>`;
const css = `.card {display:block;}\n.card:hover {color:red;}\n@media (min-width:768px){.card {display:grid;}\n.card__title {font-size:2rem;}}\n/* .card {} */`;
const card=html.indexOf('card');
const active=html.indexOf('active');
assert.equal(classAt(html,'html',card,card).name,'card');
assert.equal(classAt(html,'html',active,active+6).name,'active');
assert.equal(classAt(html,'html',card,card+2),null,'partial selections must not be treated as classes');
assert.equal(classAt(html,'html',html.indexOf('class=""')+7),null,'empty attribute has no class');
assert.equal(classAt(css,'css',css.indexOf('.card')+1).name,'card');
assert.equal(classAt(css,'css',css.indexOf('.card'),css.indexOf('.card')+5).name,'card');
assert.equal(classAt(css,'css',css.indexOf('.card')+1,css.indexOf('.card')+5).name,'card');
assert.equal(findTargets(css,'/src/style.css','css','card').length,3,'base, hover, media queries should be separate destinations');
assert.equal(findTargets(css,'/src/style.css','css','card__title').length,1);
assert.equal(findTargets(css,'/src/style.css','css','card__tit').length,0);
assert.equal(findTargets(css,'/src/index.html','css','card').length,0);
const found = findTargets(html,'/src/index.html','html','card');
assert.equal(found.length,1);
assert.equal(findTargets(html,'/src/index.html','html','missing').length,0);
assert.equal(findTargets('<div class="card card">','/src/index.vue','html','card').length,2);
assert.equal(lineAt(css,css.indexOf('card__title')).line,4);
const media = findTargets(css,'/src/style.css','css','card').find(x=>x.scope.includes('@media'));
assert.ok(media,'media query must be displayed in candidates');
console.log('✓ HTML/CSS cross navigation, exact matching, multiple scopes, no edits');
